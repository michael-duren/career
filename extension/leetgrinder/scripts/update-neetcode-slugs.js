#!/usr/bin/env node
// Regenerates neetcode-slugs.js from the problem list neetcode.io ships in
// its main bundle. Each entry there pairs a NeetCode page (ncLink) with the
// LeetCode problem it mirrors (link); NeetCode uses the same list to show
// "Leetcode <number>." on its problem pages.
//
//   node scripts/update-neetcode-slugs.js
"use strict";
const fs = require("node:fs");
const path = require("node:path");

const ORIGIN = "https://neetcode.io";
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const DIFFICULTIES = ["Easy", "Medium", "Hard"];

async function text(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

function field(entry, name) {
  const m = new RegExp(`\\b${name}:"([^"]*)"`).exec(entry);
  return m ? m[1] : "";
}

async function main() {
  const html = await text(`${ORIGIN}/`);
  const main = /<script[^>]+src="(main\.[0-9a-f]+\.js)"/.exec(html);
  if (!main) throw new Error("main bundle not found on neetcode.io");
  const bundle = await text(`${ORIGIN}/${main[1]}`);
  const entries = bundle.match(/\{problem:"[^"]*",pattern:"[^"]*",link:"[^"]*"[^{}]*\}/g) || [];

  const slugs = {};
  for (const entry of entries) {
    const nc = field(entry, "ncLink").replace(/\/$/, "");
    const lc = field(entry, "link").replace(/\/$/, "");
    if (!SLUG.test(nc) || !SLUG.test(lc)) continue;
    const number = Number(/^(\d{1,6})-/.exec(field(entry, "code"))?.[1] || 0);
    const difficulty = field(entry, "difficulty");
    const row = [lc, number, field(entry, "problem"), DIFFICULTIES.includes(difficulty) ? difficulty : ""];
    const prev = slugs[nc];
    if (prev && prev[0] !== lc) throw new Error(`${nc} maps to both ${prev[0]} and ${lc}`);
    slugs[nc] = row;
  }
  const count = Object.keys(slugs).length;
  if (count < 100) throw new Error(`only ${count} NeetCode problems found; the bundle format changed`);

  const sorted = Object.fromEntries(Object.entries(slugs).sort(([a], [b]) => a.localeCompare(b)));
  const lines = Object.entries(sorted).map(([nc, row]) => `    ${JSON.stringify(nc)}: ${JSON.stringify(row)},`);
  const out = `// Generated by scripts/update-neetcode-slugs.js from neetcode.io's problem list; do not edit.
// NeetCode problem slug -> [LeetCode slug, LeetCode number, title, difficulty].
(function (root) {
  "use strict";
  const slugs = {
${lines.join("\n")}
  };
  root.LeetgrinderNeetCodeSlugs = slugs;
  if (typeof module === "object" && module.exports) module.exports = slugs;
})(globalThis);
`;
  fs.writeFileSync(path.join(__dirname, "..", "neetcode-slugs.js"), out);
  console.log(`neetcode-slugs.js: ${count} problems`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
